// A level without a timeOfDay section takes the numbers and nothing happens: said once, as the block did.
TimeOfDay& ClockOwner(SettingContext& c)
{
    TimeOfDay& tod = c.scene.TimeOfDayRef();
    if (!tod.Present())
    {
        LOG_WARNING_ONCE(logging::LogCategory::App,
                         "--set tod.*: this level has no timeOfDay section -- the clock does nothing here");
    }
    return tod;
}

TimeOfDaySettings& Clock(SettingContext& c) { return ClockOwner(c).SettingsRef(); }

